struct b25_info
b25_info (uint32_t seq)
{
	struct b25_info info = {0};
	uint32_t seen = 0;

	do {
		unsigned n = b25_info_get_num_cycles(&info);
		unsigned off = b25_info_get_cycle(&info, n - 1U).offset;
		uint32_t mask = UINT32_C(1) << off;
		for (; (seen & mask); ++off, mask <<= 1);
		for (unsigned i = off;;) {
			i = ror32(seq, i) & 31U;
			uint32_t m = mask ^ (UINT32_C(1) << i);
			if (m <= mask) {
				if (i != off)
					return (struct b25_info){0};
				break;
			}
			mask = m;
		}
		if ((seen & mask) || !b25_info_add_cycle(&info, mask))
			return (struct b25_info){0};
		seen ^= mask;
	} while (seen != UINT32_MAX);

	return info;
}

void
b25_info_print (struct b25_info const *const info,
                struct b25_id const          id)
{
	unsigned const rot = id.rot;
	unsigned const idx = id.idx;
	uint32_t const seq = ror32(B25[idx], rot);
	unsigned const num = b25_info_get_num_cycles(info);

	printf("{0x%08" PRIx32 ", 0x%016" PRIx64 ", {%" PRIu16 ",%u,%u},"
	       " {%u", seq, info->div, b25_id_to_u16(id), idx, rot, num);
	for (unsigned n = 1; ++n < 33U; ) {
		unsigned c = b25_info_get_num_period_cycles(info, n);
		if (c)
			printf(",[%u]=%u", n, c);
	}
	(void)fputs("}, {", stdout);
	for (unsigned n = 0; n < num; ++n) {
		b25_loc x = b25_info_get_cycle(info, n);
		printf(&",{%u,%u}"[!n], (unsigned)x.offset,
		                        (unsigned)x.period);
	}
	(void)fputs("}, {", stdout);
	for (unsigned n = 0; n < num; ++n)
		printf(&",0x%" PRIx32[!n], info->mask[n]);
	puts("}},");
}

